// Turns contracts/deployments.json into Dart constants the app imports:
// flutter/lib/src/chains/deployments.g.dart.
//
// Flutter can only bundle assets from inside its own package folder, and
// deployments.json lives in contracts/, next to the deploy scripts that
// update it. So after every deploy, run this from the repo root:
//
//   dart run tool/sync_deployments.dart
// ignore_for_file: avoid_print
import 'dart:convert';
import 'dart:io';

void main() {
  final source = File('contracts/deployments.json');
  final json = jsonDecode(source.readAsStringSync()) as Map<String, dynamic>;

  final evm = json['evm'] as Map<String, dynamic>;
  final evmNetworks = evm['networks'] as Map<String, dynamic>;
  final solana = json['solana']['devnet'] as Map<String, dynamic>;
  final sui = json['sui']['testnet'] as Map<String, dynamic>;
  final cosmwasm = json['cosmwasm']['osmo-test-5'] as Map<String, dynamic>;
  final near = json['near']['testnet'] as Map<String, dynamic>;

  String str(Object? value) => value == null ? 'null' : "'$value'";

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/sync_deployments.dart from contracts/deployments.json.')
    ..writeln('// Do not edit by hand. Run `dart run tool/sync_deployments.dart` after a deploy.')
    ..writeln()
    ..writeln('/// Where the counter lives on every network.')
    ..writeln('abstract final class Deployments {')
    ..writeln('  /// The EVM counter. CREATE2 gives it the same address on every EVM network.')
    ..writeln('  static const evmCounter = ${str(evm['counter'])};')
    ..writeln()
    ..writeln('  /// The block each EVM counter was deployed in, by chain ID. Reading')
    ..writeln('  /// events starts here, so the app never scans older blocks.')
    ..writeln('  static const evmDeployBlocks = <int, int>{');
  for (final entry in evmNetworks.values) {
    final network = entry as Map<String, dynamic>;
    out.writeln('    ${network['chainId']}: ${network['deployBlock'] ?? 0},');
  }
  out
    ..writeln('  };')
    ..writeln()
    ..writeln('  static const solanaProgramId = ${str(solana['programId'])};')
    ..writeln('  static const suiPackageId = ${str(sui['packageId'])};')
    ..writeln('  static const suiRegistryId = ${str(sui['registryId'])};')
    ..writeln('  static const osmosisCodeId = ${cosmwasm['codeId']};')
    ..writeln('  static const osmosisContract = ${str(cosmwasm['contract'])};')
    ..writeln('  static const nearContract = ${str(near['contract'])};')
    ..writeln('}');

  final target = File('flutter/lib/src/chains/deployments.g.dart');
  target.writeAsStringSync(out.toString());
  print('Wrote ${target.path}');
}
